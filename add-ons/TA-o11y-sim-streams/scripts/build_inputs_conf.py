#!/usr/bin/env python3
"""Compile signalflow_programs/<domain>/*.signalflow into default/inputs.conf.

Generic over domains: every .signalflow file under signalflow_programs/<domain>/
becomes a disabled sim_modular_input stanza with its SignalFlow baked in (same
pattern as splunk_ta_sim's SAMPLE_* inputs). Stanzas ship DISABLED; the operator
sets org_id (or leaves it blank for the SIM add-on default account) and enables.

Per-file directives (optional, in leading comments):
    # input: <StanzaName>     default: filename stem, title-cased
    # index: <index>          default: sim_metrics
    # interval: <seconds>     default: 300

Run from the TA root after editing any .signalflow file:
    python3 scripts/build_inputs_conf.py
"""
from __future__ import annotations

from pathlib import Path


def ta_root() -> Path:
    return Path(__file__).resolve().parent.parent


HEADER = """# Curated SIM data streams. GENERATED by scripts/build_inputs_conf.py
# from signalflow_programs/<domain>/*.signalflow. Do not edit by hand.
#
# All stanzas ship DISABLED. To activate a stream:
#   1. (Optional) set org_id, or leave blank to use the SIM add-on's default
#      O11y account (Settings -> Data Inputs -> Splunk Infrastructure Monitoring
#      -> account). org_id only overrides that default (e.g. a second org).
#   2. Enable: Settings -> Data Inputs -> Splunk Infrastructure Monitoring
#      Data Streams -> <name> -> Enable.
#
# Requires: splunk_ta_sim (provides the sim_modular_input handler) + a configured
# O11y account/realm.
"""


def parse(path: Path) -> tuple[dict, str]:
    directives = {}
    statements = []
    for line in path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith("#") or stripped.startswith("//"):
            body = stripped.lstrip("#/ ").strip()
            for key in ("input", "index", "interval"):
                prefix = f"{key}:"
                if body.lower().startswith(prefix):
                    directives[key] = body[len(prefix):].strip()
            continue
        if not stripped.endswith(";"):
            stripped += ";"
        statements.append(stripped)
    return directives, " ".join(statements)


def main() -> int:
    root = ta_root()
    src = root / "signalflow_programs"
    files = sorted(src.glob("*/*.signalflow"))
    if not files:
        print(f"No .signalflow files under {src}")
        return 1

    out = [HEADER]
    summary = []
    current_domain = None
    for f in files:
        domain = f.parent.name
        directives, program = parse(f)
        name = directives.get("input") or f.stem.replace("-", "_").title()
        index = directives.get("index", "sim_metrics")
        interval = directives.get("interval", "300")
        if domain != current_domain:
            out.append(f"\n# ==== domain: {domain} ====")
            current_domain = domain
        out.append("")
        out.append(f"[sim_modular_input://{name}]")
        out.append(f"index = {index}")
        out.append("sourcetype = stash")
        out.append(f"interval = {interval}")
        out.append("additional_meta_data_flag = 1")
        out.append("# org_id = <your O11y org id>  ; blank = SIM add-on default org")
        out.append(f'signal_flow_programs = "{program}"')
        out.append("disabled = 1")
        metrics = program.count("data(") + program.count("histogram(")
        summary.append((domain, name, metrics, f.relative_to(root)))

    dest = root / "default" / "inputs.conf"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"Wrote {dest}")
    for domain, name, metrics, rel in summary:
        print(f"  [{name}] domain={domain} metrics={metrics} <- {rel}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
